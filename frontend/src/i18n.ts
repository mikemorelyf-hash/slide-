export type TranslationKey = keyof typeof translations.en;
export type Translator = (key: TranslationKey, values?: Record<string, string | number>) => string;

export function normalizeLanguageCode(value: unknown): LanguageCode {
  return value === 'am' ? 'am' : 'en';
}

export function createTranslator(language: LanguageCode): Translator {
  return (key, values) => translate(language, key, values);
}

export function translate(
  language: LanguageCode,
  key: TranslationKey,
  values: Record<string, string | number> = {}
): string {
  const template = (translations[language] as Record<TranslationKey, string>)[key] ?? translations.en[key];
  return Object.entries(values).reduce(
    (text, [name, value]) => text.replaceAll(`{${name}}`, String(value)),
    template
  );
}
